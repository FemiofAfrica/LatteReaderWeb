const open = async (viewport, touch = false) => {
  const page = await browser.newPage({ viewport, hasTouch: touch, isMobile: touch })
  await page.addInitScript(() => {
    window.__speech = { cancels: 0, starts: 0, rates: [], active: null }
    Object.defineProperty(window, 'SpeechSynthesisUtterance', { value: class { constructor(text) { this.text = text } } })
    Object.defineProperty(window, 'speechSynthesis', { value: {
      getVoices: () => [], cancel() { window.__speech.cancels++ }, pause() {}, resume() {},
      speak(u) { const s = window.__speech; s.starts++; s.rates.push(u.rate); s.active = u; u.onstart?.() },
    } })
  })
  await page.goto(url)
  await page.screenshot({ path: `${dir}/empty-${viewport.width}.png` })
  await page.locator('input[type=file]').setInputFiles('tests/fixtures/latte-reader-text-fixture.pdf')
  await page.waitForFunction(() => document.body.textContent.includes('Extraction complete'))
  await page.locator('canvas').waitFor()
  await page.waitForTimeout(300)
  return page
}
